#!/usr/bin/env python3
"""Generates src/font.c: a bitmap font (Latin and Cyrillic) for the messages that the client draws on the display.
The glyphs are rendered from DejaVu Sans Mono Bold (free license, https://dejavu-fonts.github.io/), so the client needs no
font library. Run it on a machine that has Pillow and the font:  python3 tools/gen_font.py > src/font.c"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
SIZE = 22
font = ImageFont.truetype(FONT, SIZE)
asc, desc = font.getmetrics()
W, H = 14, asc + desc
ranges = [(0x20, 0x7E), (0x401, 0x401), (0x410, 0x44F), (0x451, 0x451)]

out = []
out.append("/* generated by tools/gen_font.py from DejaVu Sans Mono Bold, do not edit */")
out.append('#include "font.h"')
out.append(f"const int FONT_CELL_W = {W}, FONT_CELL_H = {H};")
out.append("static const struct { uint32_t first, last; } ranges[] = { " + ", ".join(f"{{0x{a:X}, 0x{b:X}}}" for a, b in ranges) + " };")
out.append(f"static const uint16_t glyphs[][{H}] = {{")
for a, b in ranges:
    for cp in range(a, b + 1):
        im = Image.new("L", (W, H), 0)
        ImageDraw.Draw(im).text((0, asc), chr(cp), font=font, fill=255, anchor="ls")
        px = im.load()
        rows = []
        for y in range(H):
            v = 0
            for x in range(W):
                if px[x, y] >= 112: v |= 1 << (15 - x)       # bit 15 is the leftmost pixel
            rows.append(f"0x{v:04X}")
        out.append("    {" + ",".join(rows) + f"}}, /* U+{cp:04X} */")
out.append("};")
out.append("""
const uint16_t *font_glyph(uint32_t cp)
{
    unsigned idx = 0;
    for (unsigned i = 0; i < sizeof ranges / sizeof ranges[0]; i++) {
        if (cp >= ranges[i].first && cp <= ranges[i].last) return glyphs[idx + (cp - ranges[i].first)];
        idx += ranges[i].last - ranges[i].first + 1;
    }
    return glyphs['?' - 0x20];
}""")
print("\n".join(out))
